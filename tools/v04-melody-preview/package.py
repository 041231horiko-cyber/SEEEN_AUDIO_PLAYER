"""Build the private STEP 03.3 preview from the verified STEP 02.1 ZIP."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
from zipfile import ZipFile, ZIP_DEFLATED

HERE = Path(__file__).resolve().parent
BASE = "9dac3c1b658eebdee82a3d5ab05fdc5efdabd1e3"
TRACKS = ("bright-wide", "bright-narrow", "dark-wide", "dark-narrow")


def source(name):
    location = f"{BASE}:SEEEN_AUDIO_PLAYER/{name}"
    return subprocess.check_output(["git", "show", location], cwd=HERE)


def extract(code, start, end):
    return code[code.index(start):code.index(end)]


def particle_adapter():
    # Extract whole functions verbatim from the pinned STEP 02.1 renderer.
    code = source("particle-field.js").decode()
    constants = extract(code, "  var CENTER_X", "  var STOP_MS")
    constants += extract(code, "  var GOLDEN_ANGLE", "  // Below this scale")
    constants += extract(code, "  var OCCLUSION_EPSILON", "  var NARROW_FIELD_COVERED_SCALE")
    constants += extract(code, "  var COLORS", "  var PALETTES")
    geometry = extract(code, "  function clamp", "  function resetPhase")
    geometry += extract(code, "  function g(", "  function wideAmplitudePrepared")
    geometry += extract(code, "  function singleWideAmplitude", "  function narrowAmplitude(")
    geometry += extract(code, "  // Keep the fixed draw coordinates", "  function now(")
    return (
        "// Generated by package.py from STEP 02.1 " + BASE + "\n"
        "(function (root) {\n  \"use strict\";\n" + constants + geometry +
        "  root.Step021Particles = {makeWide, makeNarrow, wideDot, reflectionGeometry,\n"
        "    prepareWave, synchronizedAmplitude, COLORS, WIDE_RADIUS, NARROW_HALF,\n"
        "    CENTER_RADIUS, WIDE_COUNT, NARROW_COUNT,\n"
        "    CLIP_X, CLIP_Y, CLIP_WIDTH, CLIP_HEIGHT, CENTER_X, CENTER_Y};\n"
        "}(typeof window === \"object\" ? window : module.exports));\n"
    ).replace("  function clamp", "  var knock = root.SEEENKnockSync || (typeof require === \"function\" && require(\"./knock-sync.js\"));\n\n  function clamp", 1)


def package(original, output):
    assets = {}
    with ZipFile(original) as previous:
        assert previous.read("development/commit.txt").decode().strip() == BASE
        manifest = json.loads(previous.read("development/step01/audio-manifest.json"))
        for key in TRACKS:
            compact = json.loads(source(f"knock-data/{key}.json"))
            original_path = f"development/step01/{key}.json"
            full_bytes = previous.read(original_path)
            full = json.loads(full_bytes)
            assert all(full[k] == v for k, v in compact.items()), key
            name = compact["audioFile"]
            audio = previous.read(f"app/audio/{name}")
            sha = hashlib.sha256(audio).hexdigest()
            assert sha == compact["audioSha256"] == next(row["sha256"] for row in manifest if row["filename"] == name), name
            assets[f"audio/{name}"] = audio
            assets[f"analysis/{key}.json"] = full_bytes
        assets["analysis/audio-manifest.json"] = previous.read("development/step01/audio-manifest.json")
    assets["BarlowCondensed-SemiBold.ttf"] = source("BarlowCondensed-SemiBold.ttf")
    assets["Barlow-OFL.txt"] = source("Barlow-OFL.txt")
    assets["knock-sync.js"] = source("knock-sync.js")
    assets["step021-particles.js"] = particle_adapter()
    with ZipFile(output, "x", ZIP_DEFLATED) as archive:
        for name in ("melody-preview.html", "preview.css", "melody.js", "preview.js", "verify.js", "README.md"):
            archive.write(HERE / name, name)
        for name, value in assets.items():
            archive.writestr(name, value)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("step021_zip", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    package(args.step021_zip, args.output)
